export type TourStepKind = 'welcome' | 'info' | 'try' | 'module' | 'finish';

export interface TourStep {
  id: string;
  kind: TourStepKind;
  section: string;
  emoji: string;
  title: string;
  text: string;
  bullets?: string[];
  /** data-tour value of the element to spotlight */
  target?: string;
  /** module steps: route opened by an animated click on the sidebar item */
  path?: string;
  tryEvent?: 'click' | 'focus';
  tryHint?: string;
  needsSidebar?: boolean;
}

interface ModuleDef {
  path: string;
  emoji: string;
  title: string;
  text: string;
  bullets: string[];
}

