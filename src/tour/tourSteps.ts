export function buildTourSteps(
  user: { username?: string; firstName?: string; role?: string },
  hasTarget: (sel: string) => boolean,
): TourStep[] {
  const name = user.firstName || user.username || 'коллега';
  const roleLabel = ROLE_LABELS[user.role || ''] || user.role || 'Сотрудник';

  const steps: TourStep[] = [
    {
      id: 'welcome',
      kind: 'welcome',
      section: 'Знакомство',
      emoji: '👋',
      title: `Добро пожаловать, ${name}!`,
      text: `Ваша роль — «${roleLabel}». Я покажу только те разделы, к которым у вас есть доступ. Тур займет пару минут — поехали!`,
      bullets: ['Подсвечиваю элементы и показываю клики', 'Несколько шагов можно попробовать самому', 'Остановить тур можно в любой момент: Esc'],
    },
    {
      id: 'sidebar',
      kind: 'info',
      section: 'Навигация',
      emoji: '🧭',
      title: 'Главное меню',
      text: 'Все разделы системы собраны слева и сгруппированы по задачам. Видны только доступные вашей роли — лишнее скрыто.',
      bullets: ['Нажмите на заголовок группы, чтобы свернуть ее', 'Кнопка «Свернуть» внизу делает меню компактным'],
      target: 'sidebar',
      needsSidebar: true,
    },
  ];

  if (hasTarget('search')) {
    steps.push({
      id: 'search',
      kind: 'try',
      section: 'Инструменты',
      emoji: '🔎',
      title: 'Быстрый поиск',
      text: 'Ищите заказы, клиентов и товары, не покидая текущую страницу.',
      target: 'search',
      tryEvent: 'focus',
      tryHint: 'Нажмите на поле поиска',
    });
  }
  if (hasTarget('ai-btn')) {
    steps.push({
      id: 'ai-btn',
      kind: 'info',
      section: 'Инструменты',
      emoji: '🤖',
      title: 'AI Анализ',
      text: 'Кнопка выдает свежие рекомендации по продажам и закупкам: прогноз спроса, риск дефицита, советы по лимитам.',
      target: 'ai-btn',
    });
  }
  if (hasTarget('theme')) {
    steps.push({
      id: 'theme',
      kind: 'try',
      section: 'Инструменты',
      emoji: '🌓',
      title: 'Темная тема',
      text: 'Работаете вечером? Переключите оформление — глаза скажут спасибо. Выбор запоминается.',
      target: 'theme',
      tryEvent: 'click',
      tryHint: 'Нажмите на кнопку темы (потом можно вернуть)',
    });
  }
  if (hasTarget('bell')) {
    steps.push({
      id: 'bell',
      kind: 'info',
      section: 'Инструменты',
      emoji: '🔔',
      title: 'Уведомления',
      text: 'Новые заказы, низкий заряд телефона у агента, потеря GPS — красная точка сообщит о важном.',
      target: 'bell',
    });
  }
  if (hasTarget('profile')) {
    steps.push({
      id: 'profile',
      kind: 'info',
      section: 'Инструменты',
      emoji: '🪪',
      title: 'Ваш профиль',
      text: `Вы вошли как «${roleLabel}». Права роли настраиваются в разделе «Управление ролями».`,
      target: 'profile',
    });
  }

  MODULES.forEach((m, i) => {
    if (!hasTarget(`nav:${m.path}`)) return;
    steps.push({
      id: `module-${i}`,
      kind: 'module',
      section: 'Разделы системы',
      emoji: m.emoji,
      title: m.title,
      text: m.text,
      bullets: m.bullets,
      path: m.path,
      target: `nav:${m.path}`,
    });
  });

  const moduleCount = steps.filter((s) => s.kind === 'module').length;
  steps.push({
    id: 'finish',
    kind: 'finish',
    section: 'Готово',
    emoji: '🎉',
    title: 'Тур пройден!',
    text: `Вы познакомились с ${moduleCount} разделами SmartSale. Теперь вы знаете, где что находится. Вернуться к туру можно кнопкой «Тур» в шапке в любой момент.`,
  });

  return steps;
}
